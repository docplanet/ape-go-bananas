// Plumbing for test/sidecar/agent-*.test.ts -- the ACP half of
// docs/research/agent-protocol.md (§2, §3, §5 bullets 3-4), written by a
// context that has not seen src/sidecar/agent*.ts, src/agents/ or
// src/agent/. Builds on ./helpers.ts (spawn, request, captured stdout
// lines) and adds what the reverse direction needs: answering a request the
// sidecar sends us, and waiting for a notification by predicate.
//
// The provider under test is laid out BY HAND as an installed npx package
// (§1's prefix layout: <dataDir>/npx/mock/node_modules/mock-agent/), whose
// bin is a shim that runs test/acp/mock-agent.ts in-process (same pid, so
// ACP_TEST_PIDFILE names the sidecar's direct child and reaping can be
// asserted the way test/acp/lifecycle.test.ts does). Invoked with the Claude
// login args (claude-adapter-auth.md §2/§4) the shim instead prints two
// lines and exits 0, touching a marker file that makes the NEXT run report
// itself signed in -- the "fake login script" §5 bullet 4 calls for.
//
// The registry cache is primed through `agents/list` against a one-shot
// local fake (node:http), so <dataDir>/registry.json is fresh and in the
// sidecar's own format without a byte of network; a hand-laid copy with an
// ISO `fetchedAt` is written first so an implementation that already reads
// that shape never fetches at all.
